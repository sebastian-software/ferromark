import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";

const read = (name) => readFileSync(new URL(`../${name}`, import.meta.url), "utf8");

test("README introduces the v2 release candidate and delegates detailed documentation", () => {
  const source = read("README.md.src");
  assert.match(source, /^# Ferromark v2$/m);
  assert.match(source, /arena-allocated/);
  assert.match(source, /release-candidate/);
  // The release pull request bumps these lines together with version.txt.
  const version = read("version.txt").trim();
  assert.ok(source.includes(`npm install ferromark@${version}`), `README installs ${version}`);
  assert.ok(source.includes(`cargo add ferromark@=${version}`), `README adds ${version}`);
  assert.match(source, /docs\/migration-v2\.md/);
  assert.match(source, /node\/ferromark\/README\.md/);
  assert.match(source, /UPSTREAM\.md/);
  assert.match(source, /HtmlRendererOptions::sanitize/);
  assert.doesNotMatch(source, /OX-Content|Ox Content|^\|/m);
  assert.ok(source.split(/\s+/).length < 700, "README stays below 700 words");
  const headings = [...source.matchAll(/^#{1,2} (.+)$/gm)].map((m) => m[1]);
  assert.equal(new Set(headings).size, headings.length);
  for (const page of ["features", "correctness", "benchmarks", "architecture", "rendering"]) {
    assert.ok(source.includes(`/guide/${page}`));
    assert.ok(read(`homepage/app/routes/guide/${page}.mdx`).length > 0);
  }
  assert.match(read("README.md"), /^<!-- This file is generated by mdtheme\./);
  assert.match(read("homepage/app/routes/guide/architecture.mdx"), /UPSTREAM\.md/);
});

test("matching runtime guides offer a topic-preserving switch", () => {
  for (const runtime of ["rust", "node"]) {
    for (const topic of ["getting-started", "configuration", "pipelines", "highlighting"]) {
      const guide = read(`homepage/app/routes/${runtime}/${topic}.mdx`);
      assert.ok(guide.includes(`<RuntimeSwitch topic="${topic}" />`));
    }
  }
  const declarations = read("node/ferromark/index.d.mts")
    .split("export interface Options {")[1]
    .split("\n}")[0];
  const guide = read("homepage/app/routes/node/configuration.mdx");
  const keys = [...declarations.matchAll(/^  (\w+)\?:/gm)].map((m) => m[1]).sort();
  const documented = [...guide.matchAll(/^\|\s*`(\w+)`\s*\|/gm)].map((m) => m[1]).sort();
  assert.deepEqual(documented, keys, "Node option reference matches the public declaration");
});
