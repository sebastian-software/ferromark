import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { nameToEmoji } from "gemoji";

const scriptsDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = dirname(scriptsDirectory);
const outputPath = join(repositoryRoot, "transforms/src/emoji_data.rs");
const expectedVersion = "8.1.0";
const expectedAliases = 1913;

export async function generatedEmojiData() {
  const packageJson = JSON.parse(await readFile(join(scriptsDirectory, "package.json"), "utf8"));
  assert.equal(packageJson.devDependencies.gemoji, expectedVersion);
  assert.equal(Object.keys(nameToEmoji).length, expectedAliases);

  const entries = Object.entries(nameToEmoji).sort(([left], [right]) =>
    left < right ? -1 : left > right ? 1 : 0,
  );

  for (const [name, value] of entries) {
    assert.match(name, /^(?:\+1|[-\w]+)$/);
    assert.ok(value.length > 0, `gemoji alias ${name} must have a Unicode value`);
  }

  const rows = entries.map(
    ([name, value]) => `    (${JSON.stringify(name)}, ${JSON.stringify(value)}),`,
  );
  return [
    "// @generated by scripts/generate-gemoji-data.mjs; do not edit by hand.",
    "// Dataset: gemoji@8.1.0 nameToEmoji from the integrity-pinned npm artifact.",
    "// Source revision: wooorm/gemoji 2952469469d6e9215ce0ed391ac4193b840be89b.",
    "// Registry integrity: sha512-HA4Gx59dw2+tn+UAa7XEV4ufUKI4fH1KgcbenVA9YKSj1QJTT0xh5Mwv5HMFNN3l2OtUe3ZIfuRwSyZS5pLIWw==.",
    "// Copyright and license notice: transforms/data/LICENSE.gemoji.",
    `// ${entries.length} shortcode aliases, sorted by ASCII name.`,
    "",
    "pub static SHORTCODES: &[(&str, &str)] = &[",
    ...rows,
    "];",
    "",
  ].join("\n");
}

async function main() {
  const generated = await generatedEmojiData();
  if (process.argv.includes("--write")) {
    await writeFile(outputPath, generated);
    return;
  }

  const existing = await readFile(outputPath, "utf8");
  assert.equal(existing, generated, "run pnpm gemoji:data to regenerate the pinned dataset");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
