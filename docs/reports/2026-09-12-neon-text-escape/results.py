"""Recompute every table from complete recorded timing windows."""
from pathlib import Path
import gzip,json,statistics,sys
D=Path(__file__).resolve().parent

def rows(folder):
 raw=[json.loads(s) for s in gzip.decompress((folder/'windows.jsonl.gz').read_bytes()).decode().splitlines()]
 stored=json.loads((folder/'summary.json').read_text());result={}
 engines=['baseline']+sorted(set(x['engine'] for x in raw)-{'baseline'});assert len(engines)==2
 for row in stored:
  samples={n:[x['elapsed_ns']/x['count'] for x in raw if x['index']==row['index'] and x['engine']==n] for n in engines}
  assert all(len(v)==len(next(iter(samples.values()))) and len(v)>=5 for v in samples.values()),folder
  a,b=[statistics.median(v) for v in samples.values()];pct=(b/a-1)*100
  assert abs(row['baseline_ns']-a)<1e-6 and abs(row['candidate_ns']-b)<1e-6 and abs(row['change_pct']-pct)<1e-9,(folder,row)
  result[row['index']]=dict(row,baseline_ns=a,candidate_ns=b,change_pct=pct)
 assert len(raw)==sum(len([x for x in raw if x['index']==i]) for i in result),folder
 return result

def generate():
 text=['# Escape integration measurements','','Generated by `python3 results.py`. Negative percentages mean less elapsed time.','No implementation is accepted by this investigation.','']
 selected=json.loads((D/'selected.json').read_text())
 examples={'direct-neon':[29,44,696],'outlined-neon':[9,16,44,708,710],'tail-neon':[7,613,703,707],'bulk-neon':[9,16,708,710],'bulk-inline-neon':[9,16,29,42,708,710]}
 text += ['## Repeated control observations','','Each cell is the before/after percentage change in a fresh process pair.','Screen values are exploratory; the two follow-ups use longer windows.','','| Variant | Case | Initial pair(s) | Follow-up 1 | Follow-up 2 |','|---|---|---:|---:|---:|']
 for name,ids in examples.items():
  root=D/'measurements'/name
  initial=[rows(root/f'confirm-{i}') for i in [1,2,3]] if name=='direct-neon' else [rows(root/'screen')]
  follows=[rows(root/f'follow-{i}') for i in [1,2]]
  for i in ids:
   text.append('| '+name+' | '+initial[0][i]['case']+' | '+', '.join(f"{g[i]['change_pct']:+.2f}%" for g in initial)+' | '+' | '.join(f"{g[i]['change_pct']:+.2f}%" for g in follows)+' |')
 text += ['','## Long escape stress screen','','One complete process pair, five alternating windows of at least 30 ms.','The timer is checked after each render. These synthetic inputs are not ordinary','document speedups, and this screen does not establish a regression-free integration.','','| Case | Before µs | Single-scan µs | Change |','|---|---:|---:|---:|']
 stress=rows(D/'measurements/single-neon/regime-screen-complete')
 assert set(stress)==set(json.loads((D/'regime-selected.json').read_text()))
 for r in stress.values():text.append(f"| {r['case']} | {r['baseline_ns']/1000:.3f} | {r['candidate_ns']/1000:.3f} | {r['change_pct']:+.2f}% |")
 text += ['','## Complete ordinary corpus: direct scan','','Three fresh process pairs, seven alternating windows of at least 50 ms.','Absolute columns are medians of the three pair medians, in microseconds.','','| Case | Before µs | After µs | Pair 1 | Pair 2 | Pair 3 |','|---|---:|---:|---:|---:|---:|']
 groups=[rows(D/f'measurements/direct-neon/confirm-{i}') for i in [1,2,3]]
 assert all(set(g)==set(selected) for g in groups)
 for i in selected:
  r=[g[i] for g in groups];a=statistics.median(x['baseline_ns'] for x in r)/1000;b=statistics.median(x['candidate_ns'] for x in r)/1000
  text.append('| '+r[0]['case'].replace('|','\\|')+f' | {a:.3f} | {b:.3f} | '+' | '.join(f"{x['change_pct']:+.2f}%" for x in r)+' |')
 text.append('')
 for name in examples:
  root=D/'measurements'/name
  for f in sorted(root.iterdir()):
   if not f.is_dir() or not (f/'summary.json').exists() or f.name.startswith('confirm-'):continue
   text += ['## '+name+'/'+f.name,'','| Case | Before µs | After µs | Change |','|---|---:|---:|---:|']
   g=rows(f)
   if f.name=='screen' and name!='bulk-inline-neon':assert set(g)==set(selected),f
   for r in g.values():text.append(f"| {r['case']} | {r['baseline_ns']/1000:.3f} | {r['candidate_ns']/1000:.3f} | {r['change_pct']:+.2f}% |")
   text.append('')
 return '\n'.join(text).rstrip()+'\n'

if __name__=='__main__':
 output=generate();p=D/'RESULTS.md'
 if '--check' in sys.argv:assert p.read_text()==output
 else:p.write_text(output)
