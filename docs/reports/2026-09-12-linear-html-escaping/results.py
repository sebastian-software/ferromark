"""Generate complete measured results, including rejected experiments."""
from pathlib import Path
import gzip,json,statistics,sys
D=Path(__file__).resolve().parent

def rows(folder):
 raw=[json.loads(s) for s in gzip.decompress((folder/'windows.jsonl.gz').read_bytes()).decode().splitlines()]
 stored=json.loads((folder/'summary.json').read_text());result={}
 engines=['baseline']+sorted(set(x['engine'] for x in raw)-{'baseline'});assert len(engines)==2
 for row in stored:
  samples={n:[x['elapsed_ns']/x['count'] for x in raw if x['index']==row['index'] and x['engine']==n] for n in engines}
  assert all(len(v)==len(next(iter(samples.values()))) and len(v)>=5 for v in samples.values()),folder
  a,b=[statistics.median(v) for v in samples.values()];pct=(b/a-1)*100
  assert abs(row['baseline_ns']-a)<1e-6 and abs(row['candidate_ns']-b)<1e-6 and abs(row['change_pct']-pct)<1e-9,(folder,row)
  result[row['index']]=dict(row,baseline_ns=a,candidate_ns=b,change_pct=pct)
 assert len(raw)==sum(len([x for x in raw if x['index']==i]) for i in result),folder
 return result

def generate():
 text=['# Linear HTML escaping measurements','','Generated by `python3 results.py`. Negative changes mean less elapsed time.','Absolute columns use microseconds. Measurements are native Markdown-to-HTML,','including destruction of the owned output. Synthetic cases are explicitly named.','The label `final` belongs to a rejected intermediate experiment; `linear` is the','source proposed by this report.','']
 used=set()
 for title,prefix,selection in [('Ordinary documents','confirm','selected.json'),('Text and code stress','regime-confirm','regime-selected.json'),('Attribute stress','attribute-confirm','attribute-selected.json')]:
  text+=['## '+title,'','Three fresh process pairs. Absolute columns are medians of pair medians.','','| Case | Before µs | After µs | Pair 1 | Pair 2 | Pair 3 |','|---|---:|---:|---:|---:|---:|']
  keys=[f'linear/{prefix}-{i}' for i in [1,2,3]];used.update(keys)
  groups=[rows(D/'measurements'/key) for key in keys]
  selected=json.loads((D/selection).read_text());assert all(list(g)==selected for g in groups)
  for i in selected:
   r=[g[i] for g in groups];a=statistics.median(x['baseline_ns'] for x in r)/1000;b=statistics.median(x['candidate_ns'] for x in r)/1000
   text.append('| '+r[0]['case'].replace('|','\\|')+f' | {a:.3f} | {b:.3f} | '+' | '.join(f"{x['change_pct']:+.2f}%" for x in r)+' |')
  text.append('')
 for key in json.loads((D/'runs.json').read_text()):
  if key in used:continue
  text+=['## '+key,'','| Case | Before µs | After µs | Change |','|---|---:|---:|---:|']
  for r in rows(D/'measurements'/key).values():
   text.append('| '+r['case'].replace('|','\\|')+f" | {r['baseline_ns']/1000:.3f} | {r['candidate_ns']/1000:.3f} | {r['change_pct']:+.2f}% |")
  text.append('')
 return '\n'.join(text).rstrip()+'\n'

def focus():
 text=['The proposed source removes the quadratic rescan pattern. The ordinary',
       'code control improves in repeated pairs; the earlier multi-percent inline',
       'and table losses do not persist in this integration. Small repeated costs',
       'remain visible below. This is an algorithmic fix with disclosed sub-percent',
       'controls, not a claim that every input becomes faster.','',
       '| Case | Before µs | After µs | Primary pair changes | Longer follow-ups |',
       '|---|---:|---:|---|---|']
 def add(prefix,index,follow=False):
  r=[rows(D/f'measurements/linear/{prefix}-{i}')[index] for i in [1,2,3]]
  a=statistics.median(x['baseline_ns'] for x in r)/1000;b=statistics.median(x['candidate_ns'] for x in r)/1000
  changes=', '.join(f"{x['change_pct']:+.2f}%" for x in r)
  longer=', '.join(f"{rows(D/f'measurements/linear/follow-{i}')[index]['change_pct']:+.2f}%" for i in [1,2]) if follow else '—'
  text.append('| '+r[0]['case'].replace('|','\\|')+f' | {a:.3f} | {b:.3f} | {changes} | {longer} |')
 for i in [9,7,10,41,79,108,487,612,613]:add('confirm',i,True)
 for i in [739,741]:add('regime-confirm',i)
 for i in [9,13]:add('attribute-confirm',i)
 text+=['','In particular, inline and deep-emphasis controls retain small repeated',
        'positive differences in the longer pairs. These are not removed by A/A',
        'normalization or assumed workload weights. The complete tables preserve',
        'both those costs and the identical-binary observations. Isolated larger HTML',
        'outliers do not reproduce in the longer counterchecks.','']
 return '\n'.join(text)

if __name__=='__main__':
 output=generate();p=D/'RESULTS.md'
 report=D/'REPORT.md';current=report.read_text()
 first='<!-- measured-focus:start -->';last='<!-- measured-focus:end -->'
 expected=current[:current.index(first)+len(first)]+'\n'+focus()+current[current.index(last):]
 if '--check' in sys.argv:
  assert p.read_text()==output
  assert current==expected
 else:
  p.write_text(output);report.write_text(expected)
