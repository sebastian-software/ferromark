/*
 * Renders every sample the homepage shows with the published npm packages and
 * writes app/data/homepage-samples.json. The page imports that file; nobody
 * edits it by hand. Run it again after a release:
 *
 *   node scripts/render-homepage-samples.mjs
 *
 * Ferromark is the version in node/ferromark/package.json, the one the site
 * documents. Ferriki and Ferrigura are pinned below. The packages install into
 * a temporary directory with lifecycle scripts disabled, so the site's own
 * dependency tree stays unchanged.
 */
import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const { version: ferromarkVersion } = JSON.parse(
  await readFile(new URL("../../node/ferromark/package.json", import.meta.url), "utf8"),
);
const packages = {
  ferromark: ferromarkVersion,
  "@ferriki/core": "1.3.0",
  "@ferrigura/core": "0.7.0",
};

const directory = await mkdtemp(join(tmpdir(), "ferromark-homepage-samples-"));
try {
  await writeFile(
    join(directory, "package.json"),
    `${JSON.stringify({ private: true, type: "module", dependencies: packages }, null, 2)}\n`,
  );
  execFileSync("npm", ["install", "--ignore-scripts", "--no-audit", "--no-fund"], {
    cwd: directory,
    stdio: "inherit",
  });
  const require = createRequire(join(directory, "package.json"));
  const load = async (name) => {
    const manifest = JSON.parse(
      await readFile(join(directory, "node_modules", name, "package.json"), "utf8"),
    );
    if (manifest.version !== packages[name]) {
      throw new Error(`Installed ${name} ${manifest.version}, expected ${packages[name]}`);
    }
    return import(pathToFileURL(require.resolve(name)).href);
  };
  const fm = await load("ferromark");
  const { createHighlighter } = await load("@ferriki/core");
  const { Renderer } = await load("@ferrigura/core");

  const basic =
    "## Markdown for your pipeline\n\nFerromark renders **Markdown** with CommonMark semantics.\n\nUse `cargo add ferromark` in Rust or `npm install ferromark` in Node.js.\n";
  const ffm =
    "> Simplicity is prerequisite for reliability.\n: Edsger W. Dijkstra, *1975*\n\n| Plan | Monthly | Yearly |\n| :--- | ---: | ---: |\n| Starter | 9 € | 90 € |\n| Team | 29 € | 290 € |\n| Enterprise | On request ||\n\n: Pricing *per seat*\n\nCaptions and credits are ==plain Markdown==.^[No HTML, no shortcodes.]\nThis sentence was ++added in the second edition++.\n";
  const typography = '"Ready," she said. It\'s done...';
  // Every language the typography pass supports; the page shows a selection.
  const languages = [
    "cs",
    "da",
    "de",
    "en",
    "es",
    "fi",
    "fr",
    "it",
    "nb",
    "nl",
    "pl",
    "pt",
    "ru",
    "sv",
    "uk",
  ];
  const hostile =
    'Thanks for the review!\n\n<img src=x onerror="steal(document.cookie)">\n\n[Open the report](javascript:alert(1))\n';
  const code =
    '```rust\nfn main() -> Result<(), ferromark::ParseError> {\n    let html = ferromark::to_html("Hello, **world**!")?;\n    println!("{html}");\n    Ok(())\n}\n```\n';
  const mermaid = "```mermaid\nflowchart LR\n  Draft --> Review --> Publish\n```\n";
  const mdx =
    '# Release notes\n\nimport { Chart } from "./chart.jsx"\n\n<Chart data={sales} />\n\nShipped on **Friday**.\n';
  const analysis =
    "# Guide\n\n[Setup](/setup) ![Logo](./logo.svg)\n\n<Chart data={sales} />\n\n## Usage\n\nStatic prose with a [link](https://ferromark.dev).\n";
  const hello = "Hello, **world**!";

  const theme = "github-light-default";
  const highlighter = await createHighlighter({ themes: [theme], langs: ["rust"] });
  const hooks = fm.composeCodeHooks(
    fm.createDiagramCodeRenderer(new Renderer(), { colorScheme: "light" }),
    { highlightCodeBlock: fm.createLineHighlighter(highlighter, { theme }) },
  );
  const withHooks = (source) => {
    const result = fm.toHtmlWithCodeRenderer(source, hooks);
    return typeof result === "string" ? result : result.html;
  };
  const prepared = fm.prepareDocument(analysis, { format: "mdx" });

  const samples = {
    note: "Generated by scripts/render-homepage-samples.mjs with the npm packages in renderedWith. Do not hand-edit.",
    renderedWith: packages,
    basic: { markdown: basic, html: fm.toHtml(basic) },
    ffm: { markdown: ffm, options: '{ preset: "ffm" }', html: fm.toHtml(ffm, { preset: "ffm" }) },
    typography: {
      markdown: typography,
      outputs: Object.fromEntries(
        languages.map((language) => [
          language,
          fm.toHtml(typography, { typography: { language } }),
        ]),
      ),
    },
    trust: {
      markdown: hostile,
      untrusted: fm.toHtml(hostile),
      trusted: fm.toHtml(hostile, { renderPolicy: "trusted" }),
    },
    code: { markdown: code, theme, html: withHooks(code) },
    mermaid: { markdown: mermaid, html: withHooks(mermaid) },
    mdx: { markdown: mdx, jsx: fm.compileJsx(mdx, { format: "mdx" }).body },
    analysis: {
      markdown: analysis,
      references: prepared
        .collectReferences()
        .map(({ kind, destination, span }) => ({ kind, destination, span })),
      sections: prepared
        .extractText()
        .sections.map(({ heading, level, id }) => ({ heading, level, id })),
      diagnostics: prepared
        .projectMarkdown()
        .diagnostics.map(({ code: diagnostic, start, end }) => ({ code: diagnostic, start, end })),
    },
    hello: { markdown: hello, html: fm.toHtml(hello) },
  };

  await writeFile(
    new URL("../app/data/homepage-samples.json", import.meta.url),
    `${JSON.stringify(samples, null, 2)}\n`,
  );
  console.log(`Rendered the homepage samples with ferromark ${ferromarkVersion}`);
} finally {
  await rm(directory, { recursive: true, force: true });
}
