/* ---------- MDX and document analysis ---------- */

function OutList({ items }: { items: Array<[string, string]> }) {
  return (
    <ul className="fm-out-list">
      {items.map(([name, detail]) => (
        <li key={`${name} ${detail}`}>
          <span>{name}</span>
          <span>{detail}</span>
        </li>
      ))}
    </ul>
  );
}

