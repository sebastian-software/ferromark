/* ---------- At work ---------- */

const logos: Record<string, string> = { ardo: ardoLogo, palamedes: palamedesLogo };
const applications = [
  { name: "ardo", text: "The React documentation framework renders its pages with Ferromark." },
  { name: "palamedes", text: "Internationalization for TypeScript apps." },
].map((application) => {
  const tool = family.find((member) => member.name === application.name);
  if (tool === undefined || !(tool.runsOn ?? []).includes("ferromark")) {
    throw new Error(`The registry must say ${application.name} runs on Ferromark`);
  }
  const engines = runsOnTools(tool).map((engine) => displayName(engine));
  const runs = `${engines.slice(0, -1).join(", ")} and ${engines.at(-1) ?? ""}`;
  return { ...application, title: displayName(tool), runs };
});

export function Applications() {
  return (
    <div className="mono-wide fm-apps">
      {applications.map((application) => (
        <div className="fm-app" key={application.name}>
          <img src={logos[application.name]} alt={`${application.title} logo`} />
          <div>
            <h3>{application.title}</h3>
            <p>{application.text}</p>
            <span className="fm-runs">runs on {application.runs}</span>
          </div>
        </div>
      ))}
    </div>
  );
}
