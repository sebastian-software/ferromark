/* ---------- Trust ---------- */

/** Real output, line by line; the lines the other policy does not produce are marked. */
function Compared({ text, other }: { text: string; other: string }) {
  const otherLines = new Set(trimmed(other).split("\n"));
  const lines = trimmed(text).split("\n");
  return (
    <pre>
      {lines.map((line, index) => (
        // Output lines are fixed and never reorder.
        <span key={index}>
          <span className={otherLines.has(line) ? undefined : "fm-hit"}>{line}</span>
          {index < lines.length - 1 ? "\n" : ""}
        </span>
      ))}
    </pre>
  );
}

