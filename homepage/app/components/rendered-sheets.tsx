import type { ReactNode } from "ardo/react";

import { useEffect, useRef, useState } from "ardo/react";
import { MonoFacing, MonoSheet } from "ferramenta-family/monografie";

/**
 * Maps each source line to the top-level output block it became: blocks are
 * separated by blank lines in the source, in order. With `captions`, a line
 * that opens with ": " after a blank line is the caption of the block above it
 * (FFM's table and image captions), so it joins that block.
 */
function blockMap(lines: string[], captions: boolean): number[] {
  const map: number[] = [];
  let block = 0;
  lines.forEach((line, index) => {
    if (line.trim() === "") {
      map.push(-1);
      if (index > 0 && lines[index - 1].trim() !== "") block++;
      return;
    }
    const caption =
      captions && index > 0 && lines[index - 1].trim() === "" && line.startsWith(": ");
    if (caption) block--;
    map.push(block);
  });
  return map;
}

export type RenderedSheetsProps = {
  markdown: string;
  /** Real Ferromark output for `markdown`; fixed at build time, never visitor input. */
  html: string;
  file: string;
  call: ReactNode;
  captions?: boolean;
  caption: ReactNode;
};

type SourceProps = {
  lines: string[];
  map: number[];
  active?: number;
  onActive: (block?: number) => void;
};

function Source({ lines, map, active, onActive }: SourceProps) {
  return (
    <pre className="fm-source" aria-label="Markdown source">
      {lines.map((line, index) => (
        <span
          // Source lines are fixed and never reorder.
          key={index}
          className={active !== undefined && map[index] === active ? "fm-line fm-on" : "fm-line"}
          onMouseEnter={() => {
            if (map[index] >= 0) onActive(map[index]);
          }}
          onMouseLeave={() => {
            onActive();
          }}
        >
          {line}
        </span>
      ))}
    </pre>
  );
}

/** The source and its rendered page facing each other; a source line lights up the block it became. */
export function RenderedSheets({
  markdown,
  html,
  file,
  call,
  captions = false,
  caption,
}: RenderedSheetsProps) {
  const lines = markdown.replace(/\n$/, "").split("\n");
  const map = blockMap(lines, captions);
  const [active, setActive] = useState<number>();
  const output = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const blocks = output.current?.children;
    if (blocks === undefined) return;
    [...blocks].forEach((block, index) => {
      block.classList.toggle("fm-on", index === active);
    });
  }, [active]);
  return (
    <figure className="mono-wide">
      <MonoFacing>
        <MonoSheet label="As typed" meta={file}>
          <Source lines={lines} map={map} active={active} onActive={setActive} />
        </MonoSheet>
        <MonoSheet label="As rendered by Ferromark" meta={call}>
          <div
            className="fm-rendered"
            ref={output}
            // Generated by scripts/render-homepage-samples.mjs from the fixed source beside it.
            dangerouslySetInnerHTML={{ __html: html }}
          />
        </MonoSheet>
      </MonoFacing>
      <figcaption className="mono-caption">{caption}</figcaption>
    </figure>
  );
}
