import { type RefObject, useCallback, useEffect, useRef, useState } from "ardo/react";

import { samples } from "./homepage-data";

const order = ["en", "de", "fr", "da", "sv", "pl", "cs", "ru"] as const;
type Language = (typeof order)[number];
const LANGUAGES: Record<Language, string> = {
  en: "English",
  de: "German",
  fr: "French",
  da: "Danish",
  sv: "Swedish",
  pl: "Polish",
  cs: "Czech",
  ru: "Russian",
};
const outputs: Record<string, string> = samples.typography.outputs;
const supported = Object.keys(outputs).sort().join(", ");

/** The opening and closing quotation marks in a language's real output. */
function quotes(html: string): [string, string] {
  // Each output is one paragraph: <p>…</p>.
  const text = html
    .trim()
    .replace(/^<p>/, "")
    .replace(/<\/p>$/, "");
  const match = /^(.*?)Ready,(.*?) she/.exec(text);
  return match === null ? ["“", "”"] : [match[1].trim(), match[2].trim()];
}

const reducedMotion = () =>
  typeof matchMedia === "function" && matchMedia("(prefers-reduced-motion: reduce)").matches;

const next = (current: Language) => order[(order.indexOf(current) + 1) % order.length];

/** The shown language follows the selected one after a short fade. */
function useShown(selected: Language) {
  const [shown, setShown] = useState<Language>(selected);
  useEffect(() => {
    if (selected === shown) return;
    if (reducedMotion()) {
      setShown(selected);
      return;
    }
    const timer = setTimeout(() => {
      setShown(selected);
    }, 250);
    return () => {
      clearTimeout(timer);
    };
  }, [selected, shown]);
  return shown;
}

function useInView(target: RefObject<HTMLElement | null>) {
  const [inView, setInView] = useState(false);
  useEffect(() => {
    const element = target.current;
    if (element === null || typeof IntersectionObserver !== "function") return;
    const observer = new IntersectionObserver(
      (entries) => {
        setInView(entries.some((entry) => entry.isIntersecting));
      },
      { threshold: 0.35 },
    );
    observer.observe(element);
    return () => {
      observer.disconnect();
    };
  }, [target]);
  return inView;
}

/** Steps through the languages while running, unless motion is reduced. */
function useCycle(running: boolean, step: () => void) {
  useEffect(() => {
    if (!running || reducedMotion()) return;
    const timer = setInterval(step, 2600);
    return () => {
      clearInterval(timer);
    };
  }, [running, step]);
}

function Loupe({ selected, shown }: { selected: Language; shown: Language }) {
  const [open, close] = quotes(outputs[shown]);
  return (
    <div className="fm-loupe" aria-hidden="true">
      <div className={selected === shown ? "fm-glyphs" : "fm-glyphs fm-swap"}>
        <span>{open}</span>
        <span>{close}</span>
      </div>
      <span className="fm-loupe-language">{LANGUAGES[shown]}</span>
    </div>
  );
}

function Languages({ selected, onPick }: { selected: Language; onPick: (code: Language) => void }) {
  return (
    <div className="fm-languages" role="group" aria-label="Language">
      {order.map((code) => (
        <button
          key={code}
          type="button"
          title={LANGUAGES[code]}
          aria-label={LANGUAGES[code]}
          aria-pressed={code === selected}
          onClick={() => {
            onPick(code);
          }}
        >
          {code}
        </button>
      ))}
    </div>
  );
}

function Output({ shown }: { shown: Language }) {
  return (
    <>
      <div className="fm-sub-head">Typed</div>
      <pre className="fm-typo-in">{samples.typography.markdown}</pre>
      <div className="fm-sub-head">
        Rendered with <code>{`typography: { language: "${shown}" }`}</code>
      </div>
      <div
        className="fm-typo-out"
        aria-live="polite"
        // Generated by scripts/render-homepage-samples.mjs; fixed at build time.
        dangerouslySetInnerHTML={{ __html: outputs[shown] }}
      />
    </>
  );
}

/** The typography pass, one language at a time; it steps through them while in view. */
export function TypographyLoupe() {
  const root = useRef<HTMLDivElement>(null);
  const [selected, setSelected] = useState<Language>("en");
  const [paused, setPaused] = useState(false);
  const [picked, setPicked] = useState(false);
  const shown = useShown(selected);
  const inView = useInView(root);
  const step = useCallback(() => {
    setSelected(next);
  }, []);
  useCycle(inView && !paused && !picked, step);
  return (
    <div
      className="mono-wide fm-typo"
      ref={root}
      onMouseEnter={() => {
        setPaused(true);
      }}
      onMouseLeave={() => {
        setPaused(false);
      }}
      onFocus={() => {
        setPaused(true);
      }}
    >
      <Loupe selected={selected} shown={shown} />
      <div>
        <Output shown={shown} />
        <Languages
          selected={selected}
          onPick={(code) => {
            setPicked(true);
            setSelected(code);
          }}
        />
        <p className="mono-caption">
          Real output of each language&rsquo;s pass. Supported: {supported}.
        </p>
      </div>
    </div>
  );
}
